namespace SMART;

public sealed class CalendarControl : UserControl
{
    private static readonly Color BgColor = Color.FromArgb(13, 17, 38);
    private static readonly Color CardColor = Color.FromArgb(22, 33, 62);
    private static readonly Color AccentColor = Color.FromArgb(233, 69, 96);
    private static readonly Color TextGray = Color.FromArgb(150, 150, 170);
    private static readonly Color DimGray = Color.FromArgb(85, 85, 119);
    private readonly string employeeId;
    private readonly string instructorName;
    private readonly List<(int Id, string Title)> courses;
    private DateTime displayedMonth = new(DateTime.Today.Year, DateTime.Today.Month, 1);
    private readonly TableLayoutPanel calendarGrid = new();
    private readonly Label monthLabel = new();
    private readonly RoundedTextBox titleInput = new();
    private readonly RoundedTextBox descriptionInput = new();
    private readonly DateTimePicker eventDate = new();
    private readonly ComboBox eventType = new();
