    private Control BuildLegend()
    {
        var legend = new FlowLayoutPanel
        {
            Dock = DockStyle.Fill, BackColor = BgColor, WrapContents = false,
            FlowDirection = FlowDirection.LeftToRight, Padding = new Padding(2, 4, 0, 0)
        };
        AddLegend(legend, "Holiday", "Holiday");
        AddLegend(legend, "Exam", "Exam");
        AddLegend(legend, "Quiz", "Quiz");
        AddLegend(legend, "No Class", "No Class");
        AddLegend(legend, "Meeting", "Meeting");
        AddLegend(legend, "Event", "Event");
        AddLegend(legend, "Other", "Other");
        return legend;
    }

    private static void AddLegend(FlowLayoutPanel legend, string type, string label)
    {
        var item = new FlowLayoutPanel { AutoSize = true, WrapContents = false, Margin = new Padding(3, 0, 9, 0) };
        item.Controls.Add(new Panel { Width = 10, Height = 10, BackColor = ColorForEventType(type), Margin = new Padding(0, 4, 4, 0) });
        item.Controls.Add(new Label { Text = label, AutoSize = true, ForeColor = TextGray, Font = new Font("Segoe UI", 8F) });
        legend.Controls.Add(item);
    }

    private void LoadEvents()
    {
        monthLabel.Text = displayedMonth.ToString("MMMM yyyy");
        try
        {
            eventsByDate = new Dictionary<DateTime, List<CalendarEvent>>();
            using var connection = OpenConnection();
            using var command = new SqlCommand(@"SELECT EventId, Title, EventDate, EventType,
                    CourseId, IsAutoGenerated, Description, InstructorEmployeeID
                FROM dbo.Events
                WHERE (InstructorEmployeeID = @empId OR InstructorEmployeeID IS NULL)
                    AND YEAR(EventDate) = @year AND MONTH(EventDate) = @month
                ORDER BY EventDate, Title", connection);
            command.Parameters.Add("@empId", SqlDbType.NVarChar, 50).Value = employeeId;
            command.Parameters.Add("@year", SqlDbType.Int).Value = displayedMonth.Year;
            command.Parameters.Add("@month", SqlDbType.Int).Value = displayedMonth.Month;
            using var reader = command.ExecuteReader();
            while (reader.Read())
            {
                var item = new CalendarEvent(reader.GetInt32(0), reader.GetString(1), reader.GetDateTime(2),
                    reader.GetString(3), reader.IsDBNull(4) ? null : reader.GetInt32(4),
                    reader.GetBoolean(5), reader.IsDBNull(6) ? null : reader.GetString(6),
                    reader.IsDBNull(7) ? null : reader.GetString(7));
                if (!eventsByDate.TryGetValue(item.Date.Date, out var dayEvents))
                    eventsByDate[item.Date.Date] = dayEvents = new List<CalendarEvent>();
                dayEvents.Add(item);
            }
            message.Text = "";
        }
        catch (SqlException ex)
        {
            eventsByDate.Clear();
            message.Text = "Calendar could not load: " + ex.Message;
            message.ForeColor = AccentColor;
        }
        DrawCalendar();
    }

    private void DrawCalendar()
    {
        while (calendarGrid.Controls.Count > 7)
        {
            var control = calendarGrid.Controls[7];
            calendarGrid.Controls.RemoveAt(7);
            control.Dispose();
        }
        DateTime firstDay = displayedMonth;
        DateTime start = firstDay.AddDays(-(int)firstDay.DayOfWeek);
        DateTime today = DateTime.Today;
        for (int i = 0; i < 42; i++)
        {
            DateTime date = start.AddDays(i);
            int column = i % 7;
            int row = (i / 7) + 1;
            Color cellBack = column == 0 || column == 6 ? Color.FromArgb(18, 23, 45) : CardColor;
            var cell = new CustomPanel
            {
                Dock = DockStyle.Fill, Margin = new Padding(1), Padding = new Padding(3),
                BackColor = date.Date == today ? Color.FromArgb(60, 30, 50) : cellBack,
                BorderColor = date.Date == today ? AccentColor : Color.FromArgb(35, 43, 69),
                BorderWidth = date.Date == today ? 2 : 1, CornerRadius = 4, Cursor = Cursors.Hand,
                Tag = date
            };
            cell.Click += DayCell_Click;
            var dayNumber = new Label
            {
                Text = date.Day.ToString(), AutoSize = false, Dock = DockStyle.Top, Height = 17,
                ForeColor = date.Month == displayedMonth.Month ? Color.White : DimGray,
                Font = new Font("Segoe UI", 10F, FontStyle.Bold), BackColor = Color.Transparent,
                Cursor = Cursors.Hand, Tag = date
            };
            dayNumber.Click += DayCell_Click;
            if (eventsByDate.TryGetValue(date.Date, out var dayEvents))
            {
                var eventList = new FlowLayoutPanel
                {
                    Dock = DockStyle.Fill, FlowDirection = FlowDirection.TopDown,
                    WrapContents = false, AutoScroll = false, BackColor = Color.Transparent,
                    Margin = Padding.Empty, Padding = Padding.Empty
                };
                foreach (var ev in dayEvents.Take(2))
                {
                    var chip = MakeButton(ev.Title, ColorForEventType(ev.Type), Math.Max(35, calendarGrid.ClientSize.Width / 7 - 12), 16);
                    chip.Font = new Font("Segoe UI", 7F);
                    chip.TextAlign = ContentAlignment.MiddleLeft;
                    chip.Tag = ev;
                    chip.Margin = new Padding(0, 1, 0, 1);
                    chip.Click += EventChip_Click;
                    eventList.Controls.Add(chip);
                }
                if (dayEvents.Count > 2)
                {
                    var more = new Label
                    {
                        Text = $"+{dayEvents.Count - 2} more", AutoSize = false, Height = 15,
                        ForeColor = TextGray, Font = new Font("Segoe UI", 7F), Cursor = Cursors.Hand,
                        Tag = date
                    };
                    more.Click += DayCell_Click;
                    eventList.Controls.Add(more);
                }
                cell.Controls.Add(eventList);
            }
            cell.Controls.Add(dayNumber);
            calendarGrid.Controls.Add(cell, column, row);
        }
    }

    private void DayCell_Click(object? sender, EventArgs e)
    {
        DateTime date = sender switch
        {
            Control { Tag: DateTime taggedDate } => taggedDate,
            Control { Parent: Control { Tag: DateTime parentDate } } => parentDate,
            _ => eventDate.Value.Date
        };
        eventDate.Value = date;
        if (date.Month != displayedMonth.Month || date.Year != displayedMonth.Year)
        {
            displayedMonth = new DateTime(date.Year, date.Month, 1);
            LoadEvents();
        }
        selectedEventId = null;
        deleteButton.Enabled = false;
        message.Text = eventsByDate.TryGetValue(date.Date, out var dayEvents)
            ? string.Join(" · ", dayEvents.Select(item => item.Title)) : "Selected " + date.ToString("MMM d");
        message.ForeColor = TextGray;
    }

    private void EventChip_Click(object? sender, EventArgs e)
    {
        if (sender is not Control { Tag: CalendarEvent ev }) return;
        eventDate.Value = ev.Date;
        titleInput.Text = ev.Title;
        descriptionInput.Text = ev.Description ?? "";
        eventType.SelectedItem = NormalizeEventType(ev.Type);
        selectedEventId = ev.Id;
        deleteButton.Enabled = !ev.AutoGenerated && ev.Type != "Holiday" && IsOwnedByInstructor(ev.Id);
        message.Text = deleteButton.Enabled ? "Selected event." : "Auto-generated events cannot be deleted.";
        message.ForeColor = TextGray;
    }

    private bool IsOwnedByInstructor(int eventId)
    {
        var ev = eventsByDate.Values.SelectMany(value => value).FirstOrDefault(item => item.Id == eventId);
        return ev != null && !ev.AutoGenerated &&
            string.Equals(ev.OwnerEmployeeId, employeeId, StringComparison.OrdinalIgnoreCase);
    }

    private void AddEvent()
    {
        string title = titleInput.Text.Trim();
        string description = descriptionInput.Text.Trim();
        if (title.Length == 0 || title.Length > 200)
        {
            ShowMessage("Enter a title of 1 to 200 characters.", true);
            return;
        }
        if (description.Length > 500)
        {
            ShowMessage("Description must be 500 characters or fewer.", true);
            return;
        }
        try
        {
            using var connection = OpenConnection();
            using var command = new SqlCommand(@"INSERT INTO dbo.Events
                    (Title, Description, EventDate, EventType, CourseId, InstructorEmployeeID, IsAutoGenerated)
                VALUES (@title, @desc, @date, @type, @courseId, @empId, 0)", connection);
            command.Parameters.Add("@title", SqlDbType.NVarChar, 200).Value = title;
            command.Parameters.Add("@desc", SqlDbType.NVarChar, 500).Value = string.IsNullOrWhiteSpace(description) ? DBNull.Value : description;
            command.Parameters.Add("@date", SqlDbType.Date).Value = eventDate.Value.Date;
            command.Parameters.Add("@type", SqlDbType.NVarChar, 50).Value = eventType.SelectedItem?.ToString() ?? "Other";
            int? courseId = (coursePicker.SelectedItem as CourseChoice)?.Id;
            command.Parameters.Add("@courseId", SqlDbType.Int).Value = courseId.HasValue ? courseId.Value : DBNull.Value;
            command.Parameters.Add("@empId", SqlDbType.NVarChar, 50).Value = employeeId;
            command.ExecuteNonQuery();
            titleInput.Text = "";
            descriptionInput.Text = "";
            selectedEventId = null;
            deleteButton.Enabled = false;
            if (eventDate.Value.Month != displayedMonth.Month || eventDate.Value.Year != displayedMonth.Year)
                displayedMonth = new DateTime(eventDate.Value.Year, eventDate.Value.Month, 1);
            LoadEvents();
            ShowMessage("Event added.", false);
        }
        catch (SqlException ex) { ShowMessage("Could not add event: " + ex.Message, true); }
    }

    private void DeleteSelectedEvent()
    {
        if (!selectedEventId.HasValue) return;
        try
        {
            using var connection = OpenConnection();
            using var command = new SqlCommand(@"DELETE FROM dbo.Events
                WHERE EventId = @id AND IsAutoGenerated = 0 AND InstructorEmployeeID = @empId", connection);
            command.Parameters.Add("@id", SqlDbType.Int).Value = selectedEventId.Value;
            command.Parameters.Add("@empId", SqlDbType.NVarChar, 50).Value = employeeId;
            if (command.ExecuteNonQuery() == 0)
            {
                ShowMessage("Only your own manual events can be deleted.", true);
                return;
            }
            selectedEventId = null;
            deleteButton.Enabled = false;
            LoadEvents();
            ShowMessage("Event deleted.", false);
        }
        catch (SqlException ex) { ShowMessage("Could not delete event: " + ex.Message, true); }
    }

    private static Color ColorForEventType(string? type) => type?.Replace(" ", "", StringComparison.Ordinal).ToLowerInvariant() switch
    {
        "holiday" => Color.FromArgb(204, 34, 68),
        "exam" => Color.FromArgb(106, 13, 173),
        "quiz" => Color.FromArgb(0, 102, 204),
        "noclass" => Color.FromArgb(204, 136, 0),
        "meeting" => Color.FromArgb(0, 119, 68),
        _ => Color.FromArgb(68, 68, 102)
    };

    private static string NormalizeEventType(string type) => type.Equals("NoClass", StringComparison.OrdinalIgnoreCase)
        ? "No Class" : type;

    private void ShowMessage(string text, bool error)
    {
        message.Text = text;
        message.ForeColor = error ? AccentColor : Color.LightGreen;
    }

    private SqlConnection OpenConnection()
    {
        var connection = new SqlConnection(DatabaseConnection.ConnectionString);
        try { DatabaseConnection.Open(connection); return connection; }
        catch { connection.Dispose(); throw; }
    }

    private static CustomButton MakeButton(string text, Color color, int width, int height) => new()
    {
        Text = text, BackColor = color, ForeColor = Color.White,
        Size = new Size(width, height), BorderRadius = 6, BorderSize = 0,
        Cursor = Cursors.Hand, Font = new Font("Segoe UI", 9F, FontStyle.Bold)
    };

    private static void StyleInput(RoundedTextBox input, string placeholder)
    {
        input.FillColor = BgColor;
        input.BorderColor = AccentColor;
        input.FocusBorderColor = AccentColor;
        input.BorderRadius = 6;
        input.Font = new Font("Segoe UI", 9F);
        input.ForeColor = Color.White;
        input.PlaceholderText = placeholder;
    }

    private static void StyleDate(DateTimePicker picker)
    {
        picker.CalendarMonthBackground = CardColor;
        picker.CalendarForeColor = Color.White;
        picker.CalendarTitleBackColor = AccentColor;
        picker.CalendarTitleForeColor = Color.White;
        picker.BackColor = CardColor;
        picker.ForeColor = Color.White;
        picker.Font = new Font("Segoe UI", 9F);
        picker.Format = DateTimePickerFormat.Short;
    }

    private static void StyleCombo(ComboBox combo)
    {
        combo.BackColor = BgColor;
        combo.ForeColor = Color.White;
        combo.Font = new Font("Segoe UI", 9F);
    }

    private static Label MakeFieldLabel(string text) => new()
    {
        Text = text, Dock = DockStyle.Fill, ForeColor = TextGray,
        TextAlign = ContentAlignment.MiddleLeft, Font = new Font("Segoe UI", 8F)
    };

    private sealed record CourseChoice(int? Id, string Name)
    {
        public override string ToString() => Name;
    }
}
